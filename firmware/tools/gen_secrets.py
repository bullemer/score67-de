#!/usr/bin/env python3
"""Writes include/secrets.h (gitignored) from ~/.score67-wifi: line 1 = Wi-Fi
name, line 2 = password. Development only; in the field the panel gets its
networks from the setup portal (NVS). Without the file the header is empty."""
from pathlib import Path

source = Path.home() / ".score67-wifi"
target = Path(__file__).resolve().parent.parent / "include" / "secrets.h"
lines = source.read_text().splitlines() if source.exists() else []
ssid, password = (lines + ["", ""])[:2]
escape = lambda v: v.replace("\\", "\\\\").replace('"', '\\"')
target.write_text("#pragma once\n// Generated by tools/gen_secrets.py - not committed.\n"
                  f'#define DEV_WIFI_SSID "{escape(ssid.strip())}"\n#define DEV_WIFI_PASSWORD "{escape(password.strip())}"\n')
print(f"{target}: ssid {'set' if ssid.strip() else 'EMPTY'}")
